  -- de 120400, 120410 o esta migración), no Finanzas a mano.
  create temp table vigente_d42 on commit drop as
  select l.id as lote_insumo_id, l.insumo_id, c.id, c.importe, c.moneda, c.tipo_cambio, c.cantidad, c.unidad,
         c.fecha_costo,
